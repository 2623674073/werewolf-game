from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True, slots=True)
class CharacterProfile:
    character: str
    persona_tags: tuple[str, ...]
    temperament: str
    speech_intensity: int
    sentence_style: str
    rhetorical_habits: str
    roleplay_instructions: str


def _profile(
    character: str,
    tags: tuple[str, str],
    temperament: str,
    intensity: int,
    sentence_style: str,
    rhetorical_habits: str,
    instructions: str,
) -> CharacterProfile:
    return CharacterProfile(
        character=character,
        persona_tags=tags,
        temperament=temperament,
        speech_intensity=intensity,
        sentence_style=sentence_style,
        rhetorical_habits=rhetorical_habits,
        roleplay_instructions=instructions,
    )


